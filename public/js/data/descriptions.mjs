// A Unique Skill's description, from { name, kind, element }
export function uniqueDescription(u) {
  if (!u) return '';
  if (UNIQUE_DESC[u.name]) return `${UNIQUE_DESC[u.name]}${u.kind === 'appraise' ? '' : ` ${UNIQUE_KIND_USE[u.kind] || ''}`}`.trim();
  const word = Object.keys(UNIQUE_WORD_LOOK).filter((w) => u.name.startsWith(`${w} `)).sort((a, b) => b.length - a.length)[0];
  const calls = word ? `${u.name} calls up ${UNIQUE_WORD_LOOK[word]}. ` : '';
  return `${calls}${UNIQUE_ELEMENT_LOOK[u.element] || ''} ${UNIQUE_KIND_USE[u.kind] || ''}`.trim().replace(/\s+/g, ' ');
}
